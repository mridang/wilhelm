package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

func writeFile(t *testing.T, root, rel, body string) {
	t.Helper()
	p := filepath.Join(root, filepath.FromSlash(rel))
	require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o755))
	require.NoError(t, os.WriteFile(p, []byte(body), 0o644))
}

func fixture(t *testing.T) config {
	t.Helper()
	src := t.TempDir()
	writeFile(t, src, "pkg/crd/v1/types.go", `package v1

import (
	"example.com/up/pkg/config"
	other "example.com/up/pkg/other"
)

type Thing struct {
	Mode  config.Mode
	Inner *config.Inner
	Extra other.Extra
}
`)
	writeFile(t, src, "pkg/crd/v1/zz_generated.deepcopy.go", `package v1

func (in *Thing) DeepCopy() *Thing { return in }
`)
	writeFile(t, src, "pkg/crd/v1/types_test.go", `package v1

import "testing"

func TestIgnored(t *testing.T) {}
`)
	writeFile(t, src, "pkg/config/config.go", `package config

import "net/http"

type Mode string

const (
	ModeA Mode = "a"
	ModeB Mode = "b"
)

const Unrelated = "x"

type Inner struct {
	Nested *Nested
	Client *http.Client
}

type Nested struct{ Name string }

type Unused struct{ Name string }

func (in *Inner) DeepCopy() *Inner { return in }

func (in *Inner) SetDefaults() {}

func (in *Unused) DeepCopy() *Unused { return in }
`)
	writeFile(t, src, "pkg/other/other.go", `package other

type Extra struct{ Value int }
`)
	return config{
		module:    "example.com/up",
		srcDir:    src,
		entry:     "pkg/crd/v1",
		out:       filepath.Join(t.TempDir(), "gen"),
		outImport: "example.com/me/upstream",
		trimPath:  "pkg/",
	}
}

func read(t *testing.T, cfg config, rel string) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(cfg.out, filepath.FromSlash(rel)))
	require.NoError(t, err)
	return string(b)
}

func TestRunCopiesEntryPackageWholeAndRewritesImports(t *testing.T) {
	cfg := fixture(t)
	require.NoError(t, run(cfg))

	types := read(t, cfg, "crd/v1/types.go")
	require.Contains(t, types, `"example.com/me/upstream/config"`)
	require.Contains(t, types, `other "example.com/me/upstream/other"`)
	require.NotContains(t, types, "example.com/up/")
	require.Contains(t, read(t, cfg, "crd/v1/zz_generated.deepcopy.go"), "func (in *Thing) DeepCopy()")
	require.NoFileExists(t, filepath.Join(cfg.out, "crd", "v1", "types_test.go"))
}

func TestRunExtractsOnlyReachableDeclarations(t *testing.T) {
	cfg := fixture(t)
	require.NoError(t, run(cfg))

	got := read(t, cfg, "config/zz_extracted.go")
	for _, want := range []string{"type Mode string", "ModeA", "ModeB", "type Inner struct", "type Nested struct", "func (in *Inner) DeepCopy()", `"net/http"`} {
		require.Contains(t, got, want)
	}
	for _, unwanted := range []string{"Unused", "Unrelated", "SetDefaults"} {
		require.NotContains(t, got, unwanted)
	}
	require.Contains(t, read(t, cfg, "other/zz_extracted.go"), "type Extra struct")
}

func TestRunStampsGeneratedHeaderWithUpstreamVersion(t *testing.T) {
	cfg := fixture(t)
	cfg.version = "v9.9.9"
	require.NoError(t, run(cfg))

	first, _, _ := strings.Cut(read(t, cfg, "config/zz_extracted.go"), "\n")
	require.Equal(t, "// Code generated by upstreamgen from example.com/up v9.9.9. DO NOT EDIT.", first)
}

func TestRunFailsWhenReferencedTypeIsMissingUpstream(t *testing.T) {
	cfg := fixture(t)
	writeFile(t, cfg.srcDir, "pkg/crd/v1/more.go", `package v1

import "example.com/up/pkg/other"

type More struct{ Gone other.Missing }
`)
	err := run(cfg)
	require.ErrorContains(t, err, "type Missing not found in pkg/other")
}
